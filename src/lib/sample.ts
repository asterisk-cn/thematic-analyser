import { store } from '../store.svelte';
import { parsePlainText } from './parse';

const SAMPLE = `[00:00:02] 聞き手: 今日はリモートワークについて伺います。まず、働き方はどう変わりましたか？
[00:00:09] 参加者A: 通勤がなくなったのは本当に大きいです。朝の一時間半がまるごと自分の時間になりました。
[00:00:18] 参加者A: ただ、仕事とプライベートの境目がぼやけてしまって、夜遅くまでメールを見てしまうことが増えました。
[00:00:29] 聞き手: 境目がぼやける、というのは具体的にはどんな感じですか？
[00:00:34] 参加者A: リビングで仕事をしているので、パソコンが常に視界に入るんです。閉じても頭の中では仕事が続いている感じがします。
[00:00:46] 参加者B: 私は逆で、書斎を作ってドアを閉めたら仕事は終わり、と決めています。物理的な区切りがあると楽ですね。
[00:00:57] 聞き手: チームとのコミュニケーションはいかがですか？
[00:01:02] 参加者B: 雑談が減ったのが一番寂しいです。オフィスだと廊下で何気なく相談できたことが、今は全部チャットで「わざわざ」送らないといけない。
[00:01:15] 参加者A: 分かります。ちょっとした質問をするのに気を遣うようになりました。相手の時間を奪ってしまう気がして。
[00:01:26] 参加者B: その一方で、会議は減りましたし、集中できる時間は明らかに増えています。
[00:01:35] 聞き手: 評価や成果の見え方についてはどうでしょう？
[00:01:40] 参加者A: 見られていない分、成果で示さなきゃというプレッシャーはあります。頑張っている過程が伝わらないので。
[00:01:52] 参加者B: 上司との一対一の面談を週に一度入れてもらってから、その不安はかなり減りました。
[00:02:03] 聞き手: 最後に、今後も今の働き方を続けたいですか？
[00:02:08] 参加者A: 基本は続けたいです。ただ、週に一度くらいは顔を合わせる日があったほうが、チームとしてまとまれる気がします。
[00:02:19] 参加者B: 同感です。完全リモートより、選べることが大事なんだと思います。`;

export function loadSample() {
  const doc = store.addDoc({ name: 'サンプル：リモートワーク座談会', segments: parsePlainText(SAMPLE) });

  // 上位ラベル → 下位ラベル
  const top1 = store.addLabel('働く場所と生活の境界を引き直す');
  store.updateLabel(top1.id, { description: '仕事と生活の境目を、人がどう引き直しているか。' });
  const l1 = store.addLabel('境界が溶ける', top1.id);
  const l2 = store.addLabel('物理的に区切る', top1.id);
  const top2 = store.addLabel('偶発的なつながりの喪失');
  const l3 = store.addLabel('声をかけるコストが上がる', top2.id);
  store.addLabel('見えなさへの不安');

  const mk = (seg: number, from: string, to: string | null, code: string, labelId: string | null) => {
    const t = doc.segments[seg].text;
    const a = t.indexOf(from);
    const b = to ? t.indexOf(to) + to.length : t.length;
    store.addExcerpt({ docId: doc.id, startSeg: seg, startOff: a, endSeg: seg, endOff: b, text: t.slice(a, b), code, labelId });
  };
  mk(1, '通勤', '自分の時間になりました。', '通勤がなくなり自分の時間が増えた', null);
  mk(2, '仕事と', 'ぼやけてしまって', '仕事と私生活の境目があいまいになる', l1.id);
  mk(4, '閉じても', null, '作業を終えても頭の中で仕事が続く', l1.id);
  mk(5, '書斎', '決めています。', '部屋を分けて仕事の終わりを決めている', l2.id);
  mk(7, '雑談', '寂しいです。', '雑談が減って寂しい', top2.id);
  mk(8, 'ちょっとした', null, '小さな質問をするのに遠慮してしまう', l3.id);
  store.toast('サンプルを読み込みました。文章を選択して、その切片が言っていることを書いてみてください');
}
